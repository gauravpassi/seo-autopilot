/**
 * Shopify adapter (Admin GraphQL API, default version 2026-10).
 *
 * See docs/research/research-shopify.md for the API facts this relies on.
 *
 * What it writes:
 *  - product / collection SEO title + description via `productUpdate(product:)` / `collectionUpdate(collection:)`
 *  - page / article / blog SEO title + description via the `global.title_tag` / `global.description_tag`
 *    metafields (metafieldsSet with compareDigest)
 *  - noindex via the `seo.hidden` metafield (value "1", number_integer); index again = delete it
 *  - product media alt text via `fileUpdate` (only `id` + `alt`, never `referencesToRemove`)
 *  - redirects via `urlRedirectCreate/Update/Delete`
 *  - JSON-LD as an array of schema objects in metafield `seo_agent.jsonld` (type json) on the resource
 *    (or on the shop for "/"), printed by integrations/shopify/seo-agent-jsonld.liquid
 *  - page / article body find-and-replace (exactly one occurrence)
 *
 * Everything else (h1 = product name, slug, canonical, og tags, robots.txt, llms.txt, hreflang,
 * homepage title/description, internal links) is manual: it lives in the theme or changes
 * merchant-facing data in ways we don't automate.
 */
