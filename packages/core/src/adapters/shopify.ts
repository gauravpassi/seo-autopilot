const RESERVED_SECTIONS = new Set(["products", "collections", "pages", "blogs"]);
const LOCALE_RE = /^[a-z]{2,3}(-[a-z0-9]{2,4})?$/i;

/** Parse a storefront URL or path into the Shopify resource it shows. Null = not an SEO-editable resource. */
export function parseShopifyPath(urlOrPath: string): ParsedPath | null {
  let path: string;
  try {
    path = new URL(urlOrPath, "https://placeholder.invalid").pathname;
  } catch {
    return null;
  }
  const segs = path
    .split("/")
    .filter(Boolean)
    .map((s) => {
      try {
        return decodeURIComponent(s);
      } catch {
        return s;
      }
    });
  // Strip a market/locale prefix such as /en-us or /fr.
  if (segs.length > 0 && LOCALE_RE.test(segs[0]!) && !RESERVED_SECTIONS.has(segs[0]!.toLowerCase())) {
    if (segs.length === 1 || RESERVED_SECTIONS.has(segs[1]!.toLowerCase())) segs.shift();
  }
  if (segs.length === 0) return { kind: "site" };
  const [section, a, b, c] = segs.map((s) => s.toLowerCase());
  switch (section) {
    case "products":
      return a && segs.length === 2 ? { kind: "product", handle: a } : null;
    case "collections":
      if (a && segs.length === 2) return a === "all" ? null : { kind: "collection", handle: a };
      if (a && b === "products" && c && segs.length === 4) return { kind: "product", handle: c };
      return null;
    case "pages":
      return a && segs.length === 2 ? { kind: "page", handle: a } : null;
    case "blogs":
      if (a && segs.length === 2) return { kind: "blog", handle: a };
      if (a && b && b !== "tagged" && segs.length === 3) return { kind: "article", blogHandle: a, handle: b };
      return null;
    default:
      return null;
  }
}

/** Whether a change type can be applied on a resource of this kind. */
export function shopifySupports(type: ChangeType, kind: ShopifyKind): boolean {
  switch (type) {
    case "title":
    case "meta_description":
    case "robots_meta":
      return kind === "product" || kind === "collection" || kind === "page" || kind === "article" || kind === "blog";
    case "image_alt":
      return kind === "product";
    case "redirect":
      return true; // shop-level
    case "jsonld_add":
    case "jsonld_fix":
      return true; // any resource, plus the shop for "/"
    case "content_edit":
      return kind === "page" || kind === "article";
    default:
      return false;
  }
}

/** Normalize an image URL to a comparable file key (basename without size suffix / query). */
export function imageKey(src: string): string {
  let p = src.trim();
  try {
    p = new URL(p, "https://x.invalid").pathname;
  } catch {
    p = p.split("?")[0]!;
  }
  let base = p.split("/").pop() ?? "";
  try {
    base = decodeURIComponent(base);
  } catch {
    /* keep */
  }
  base = base.toLowerCase();
  // Shopify size/crop suffixes: name_800x.jpg, name_800x600.jpg, name_800x600_crop_center.jpg, name@2x.jpg
  base = base.replace(/(_(\d+x\d*|\d*x\d+|pico|icon|thumb|small|compact|medium|large|grande|original|master)(_crop_[a-z]+)?)?(@\dx)?(\.[a-z0-9]+)$/, "$5");
  return base;
}

function schemaTypes(block: unknown): string[] {
  if (!block || typeof block !== "object") return [];
  const t = (block as Record<string, unknown>)["@type"];
  if (typeof t === "string") return [t];
  if (Array.isArray(t)) return t.filter((x): x is string => typeof x === "string");
  return [];
}

function parseJsonldValue(value: string | null): Record<string, unknown>[] {
  if (!value) return [];
  let parsed: unknown;
  try {
    parsed = JSON.parse(value);
  } catch {
    return [];
  }
  if (Array.isArray(parsed)) return parsed.filter((x): x is Record<string, unknown> => !!x && typeof x === "object");
  if (parsed && typeof parsed === "object") return [parsed as Record<string, unknown>];
  return [];
}

const sameText = (a: string | null | undefined, b: string | null | undefined) => (a ?? "").trim() === (b ?? "").trim();
const emptyToNull = (s: string | null | undefined): string | null => (s && s.trim() !== "" ? s : null);

function normalizeShop(shop: string): string {
  let s = shop.trim().replace(/^https?:\/\//i, "").replace(/\/.*$/, "").toLowerCase();
  if (!s.includes(".")) s = `${s}.myshopify.com`;
  return s;
}

function countOccurrences(hay: string, needle: string): number {
  if (!needle) return 0;
  let n = 0;
  let i = hay.indexOf(needle);
  while (i !== -1) {
    n++;
    i = hay.indexOf(needle, i + needle.length);
  }
  return n;
}

export class ShopifyUserError extends Error {
  constructor(
    public readonly operation: string,
    public readonly errors: Array<{ field?: string[] | null; message: string; code?: string | null }>,
  ) {
    super(
      `Shopify ${operation} failed: ` +
        errors.map((e) => `${e.field && e.field.length ? e.field.join(".") + ": " : ""}${e.message}${e.code ? ` (${e.code})` : ""}`).join("; "),
    );
    this.name = "ShopifyUserError";
  }
}

export class ShopifyConcurrentEditError extends Error {
  constructor(what: string) {
    super(
      `${what} was edited in Shopify after the agent read it (most likely by a merchant in the admin). ` +
        `Refusing to overwrite their edit; re-read the page and propose again.`,
    );
    this.name = "ShopifyConcurrentEditError";
  }
}

